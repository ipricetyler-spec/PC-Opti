function clone(value) {
  return JSON.parse(JSON.stringify(value));
}

function resolveRuntimeProfile({ packageDefault = 'owner', environmentOverride, isPackaged = true } = {}) {
  const configured = !isPackaged && environmentOverride !== undefined ? environmentOverride : packageDefault;
  if (!RUNTIME_PROFILES.includes(configured)) {
    throw new Error(`Runtime profile must be one of: ${RUNTIME_PROFILES.join(', ')}.`);
  }
  return configured;
}

function capabilityById(capabilityId) {
  return CAPABILITIES.find((capability) => capability.id === capabilityId) || null;
}

function assertCurrentProcessAdministrator(capabilityId, elevated, message) {
  const capability = capabilityById(capabilityId);
  if (!capability) throw new Error(`Capability ${capabilityId} is not registered.`);
  if (capability.executionAuthority.mode !== EXECUTION_AUTHORITY_MODES.CURRENT_PROCESS_ADMIN) {
    throw new Error(`Capability ${capabilityId} is not registered for current-process Administrator execution.`);
  }
  if (elevated !== true) {
    throw new Error(message || 'This change requires Dialed to be running as administrator. Close Dialed, start it again and accept the Windows administrator prompt, then retry.');
  }
  return clone(capability.executionAuthority);
}

function listCapabilities(profile) {
  if (profile === undefined) return clone(CAPABILITIES);
  if (!RUNTIME_PROFILES.includes(profile)) throw new Error('Runtime profile is not valid.');
  return clone(CAPABILITIES.filter((capability) => capability.profiles.includes(profile) || (profile === 'consumer-premium' && capability.profiles.includes('public'))));
}

function isCapabilityAvailable(capabilityId, profile) {
  const capability = capabilityById(capabilityId);
  return Boolean(capability && RUNTIME_PROFILES.includes(profile) && (capability.profiles.includes(profile) || (profile === 'consumer-premium' && capability.profiles.includes('public'))));
}

function requireCapability(capabilityId, profile) {
  const capability = capabilityById(capabilityId);
  if (!capability || !isCapabilityAvailable(capabilityId, profile)) {
    throw new Error(`Capability ${capabilityId} is unavailable in the ${profile} runtime profile.`);
  }
  return clone(capability);
}

function capabilityForAction(actionId) {
  const id = String(actionId || '');
  if (/^startup:disable:[a-f0-9]{24}$/.test(id)) return capabilityById('startup:disable-current-user-run');
  if (/^startup:disable-machine:[a-f0-9]{24}$/.test(id)) return capabilityById('startup:disable-machine-run');
  if (/^process:enable-ecoqos:\d+$/.test(id)) return capabilityById('process:enable-ecoqos');
  if (id === 'policy:disable-windows-consumer-features') return capabilityById('policy:disable-windows-consumer-features');
  if (id === 'timing:restore-automatic-clock-source') return capabilityById('timing:restore-automatic-clock-source');
  if (id === 'timing:disable-dynamic-tick') return capabilityById('timing:disable-dynamic-tick');
  if (id === 'clear-temp-files') return capabilityById('maintenance:clear-temp-files');
  if (id === 'clear-shader-caches') return capabilityById('maintenance:clear-shader-caches');
  if (id === 'clear-crash-dumps') return capabilityById('maintenance:clear-crash-dumps');
  if (/^power:activate-plan:[0-9a-f]{8}-[0-9a-f]{4}-[0-9a-f]{4}-[0-9a-f]{4}-[0-9a-f]{12}$/.test(id)) return capabilityById('power:switch-plan');
  if (/^graphics:gpu-preference:[a-f0-9]{24}$/.test(id)) return capabilityById('graphics:per-app-gpu-preference');
  if (id === 'settings:user:game-mode') return capabilityById('gaming:game-mode');
  if (id === 'settings:user:background-recording') return capabilityById('gaming:background-recording');
  if (id === 'settings:user:mouse-acceleration') return capabilityById('input:mouse-acceleration');
  if (id === 'power:add-ultimate-plan') return capabilityById('power:ultimate-plan');
  if (/^power:cpu-minimum-state:[0-9a-f]{8}-[0-9a-f]{4}-[0-9a-f]{4}-[0-9a-f]{4}-[0-9a-f]{12}$/.test(id)) return capabilityById('power:cpu-minimum-state');
  if (id === 'settings:machine:block-background-apps') return capabilityById('policy:block-background-apps');
  if (id === 'settings:machine:exclude-driver-updates') return capabilityById('policy:exclude-windows-update-drivers');
  if (id === 'settings:machine:no-auto-restart') return capabilityById('policy:no-auto-restart-signed-in');
  if (id === 'settings:machine:gpu-scheduling') return capabilityById('graphics:hardware-gpu-scheduling');
  if (id === 'settings:machine:mpo') return capabilityById('graphics:multiplane-overlay');
  if (id === 'settings:machine:global-timer-resolution') return capabilityById('timing:global-timer-resolution');
  if (/^retrim-drive:[A-Z]$/.test(id)) return capabilityById('maintenance:retrim-drive');
  if (/^optional-app:remove:[a-z0-9-]{2,64}$/.test(id)) return capabilityById('windows:optional-app-remove-current-user');
  return null;
}

